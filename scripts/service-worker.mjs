// Writes sw.js for the website so RipTide Tools works offline once it's been opened.
// It caches only this app's own files from this site: nothing from anywhere else, and no user data
// (that stays in the browser's storage). A new build gets a new cache name, so updates replace it.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

function walk(dir) {
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

export function writeServiceWorker(out) {
  const files = walk(out).map((p) => relative(out, p).split("\\").join("/"));
  // The app shell and data are cached up front; map tiles are cached as they're viewed.
  const shell = files.filter((f) => !/^map\/leonida\/\d+\//.test(f) && f !== "sw.js" && !f.endsWith(".map"));
  const hash = createHash("sha256");
  for (const f of shell.sort()) hash.update(f).update(readFileSync(join(out, f)));
  const version = hash.digest("hex").slice(0, 12);
  const sw = `// Generated by scripts/service-worker.mjs. Caches RipTide's own files for offline use.
const VERSION = ${JSON.stringify(version)};
const SHELL = "riptide-shell-" + VERSION;
const TILES = "riptide-tiles-v1";
const FILES = ${JSON.stringify(["./", ...shell.map((f) => `./${f}`)])};

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(SHELL).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("riptide-shell-") && k !== SHELL).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (e) => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== "GET" || url.origin !== self.location.origin) return; // never touch other sites
  if (/\\/map\\/leonida\\/\\d+\\//.test(url.pathname)) {
    e.respondWith(
      caches.open(TILES).then((c) => c.match(req).then((hit) => hit || fetch(req).then((res) => (res.ok && c.put(req, res.clone()), res)))),
    );
    return;
  }
  if (req.mode === "navigate") {
    // The page itself: fresh when online, the cached copy when offline.
    e.respondWith(fetch(req).catch(() => caches.match("./index.html", { ignoreSearch: true })));
    return;
  }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req)));
});
`;
  writeFileSync(join(out, "sw.js"), sw);
  return { version, files: shell.length };
}
