import type { Blueprint } from "../blueprint";
import type { BuildResult } from "./types";

/** Self-hosting: a docker-compose stack for people who bring their own machine. */
export function buildDockerStack(bp: Blueprint): BuildResult {
  const compose = `# Generated by Riptide. Run: docker compose up -d
services:
  game:
    image: ghcr.io/dosukasol/riptide-fxserver:latest
    restart: unless-stopped
    ports:
      - "30120:30120/tcp"
      - "30120:30120/udp"
      # Admin panel stays on this machine. Reach it over SSH or a VPN, never the open internet.
      - "127.0.0.1:40120:40120"
    environment:
      CFX_LICENSE_KEY: \${CFX_LICENSE_KEY}
      DATABASE_URL: mysql://riptide:\${DB_PASSWORD:?Set DB_PASSWORD in .env}@db/riptide
    volumes:
      - ./server-data:/opt/server-data
    depends_on: [db]
  db:
    image: mariadb:11
    restart: unless-stopped
    environment:
      MARIADB_DATABASE: riptide
      MARIADB_USER: riptide
      MARIADB_PASSWORD: \${DB_PASSWORD:?Set DB_PASSWORD in .env}
      MARIADB_RANDOM_ROOT_PASSWORD: "1"
    volumes:
      - db:/var/lib/mysql
  agent:
    image: ghcr.io/dosukasol/riptide-agent:latest
    restart: unless-stopped
    environment:
      RIPTIDE_SERVER: ${bp.meta.slug}
      BACKUP_EVERY_HOURS: "${bp.ops.backups.everyHours}"
      BACKUP_KEEP: "${bp.ops.backups.keep}"
    volumes:
      - ./server-data:/opt/server-data
      - ./backups:/backups
volumes:
  db: {}
`;
  const env = `# Copy to .env, fill these in, then run docker compose up -d\n# Use a long random database password, e.g. from: openssl rand -base64 32\nCFX_LICENSE_KEY=\nDB_PASSWORD=\n`;
  return {
    target: "docker",
    notes: ["Images are published when the first public build ships."],
    files: [
      { path: "docker-compose.yml", contents: compose },
      { path: ".env.example", contents: env },
    ],
  };
}
